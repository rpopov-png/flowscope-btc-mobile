@app.get('/api/state')
async def state(tf: str=Query('4h')):
    d=await fetch_market(tf)
    if d.get('ok'): save_snapshot(d); return d
    return JSONResponse(d,status_code=502)

@app.get('/api/history')
async def history(tf:str='4h',limit:int=200):
    limit=max(1,min(limit,1000))
    with engine.begin() as conn:
        rows=conn.execute(text('SELECT ts,price,spot_z,futures_z,oi_z,oi_change,funding_z,funding_rate,etf_daily,regime,confidence FROM snapshots WHERE tf=:tf ORDER BY ts DESC LIMIT :lim'),{'tf':tf,'lim':limit}).mappings().all()
    return {'ok':True,'rows':[dict(r) for r in reversed(rows)]}

