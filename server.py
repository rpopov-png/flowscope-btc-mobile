async def get_json(client,url,headers=None):
    r=await client.get(url,headers=headers or {},timeout=15.0)
    r.raise_for_status(); return r.json()

async def fetch_farside(client):
    try:
        r=await client.get('https://farside.co.uk/btc/',headers={'User-Agent':'Mozilla/5.0'},timeout=15.0)
        r.raise_for_status()
        soup=BeautifulSoup(r.text,'html.parser')
        rows=[]
        for tr in soup.find_all('tr'):
            cells=[c.get_text(' ',strip=True) for c in tr.find_all(['td','th'])]
            if not cells: continue
            if re.match(r'^\d{2}\s+[A-Za-z]{3}\s+\d{4}$',cells[0]):
                raw=cells[-1].replace(',','').strip()
                if raw in {'-',''}: continue
                neg=raw.startswith('(') and raw.endswith(')')
                raw=raw.strip('()$ ')
                try:
                    val=float(raw); val=-val if neg else val
                    rows.append((cells[0],val))
                except: pass
        if not rows: return {'status':'Unavailable','daily':None,'d3':None,'momentum5':None,'date':None}
        vals=[v for _,v in rows]
        daily=vals[-1]
        d3=sum(vals[-3:]) if len(vals)>=3 else sum(vals)
        prev5=mean(vals[-10:-5]) if len(vals)>=10 else mean(vals[:-5]) if len(vals)>5 else 0.0
        last5=mean(vals[-5:]) if len(vals)>=5 else mean(vals)
        momentum=last5-prev5
        status,cls=etf_class(daily,d3,momentum)
        return {'status':status,'cls':cls,'daily':daily,'d3':d3,'momentum5':momentum,'date':rows[-1][0]}
    except Exception as e:
        return {'status':'Unavailable','cls':'off','daily':None,'d3':None,'momentum5':None,'date':None,'error':str(e)[:160]}

async def fetch_market(tf='4h'):
    tf=tf if tf in {'1h','4h','1d','1w'} else '4h'
    limit=120 if tf=='1w' else 100
    bybit_tf={'1h':'1h','4h':'4h','1d':'1d','1w':'1d'}[tf]
    errors=[]
    async with httpx.AsyncClient(follow_redirects=True) as client:
        tasks=[
            get_json(client,f'https://api.binance.com/api/v3/klines?symbol=BTCUSDT&interval={tf}&limit={limit}'),
            get_json(client,f'https://fapi.binance.com/fapi/v1/klines?symbol=BTCUSDT&interval={tf}&limit={limit}'),
            get_json(client,f'https://api.bybit.com/v5/market/open-interest?category=linear&symbol=BTCUSDT&intervalTime={bybit_tf}&limit=60'),
            get_json(client,'https://api.bybit.com/v5/market/funding/history?category=linear&symbol=BTCUSDT&limit=100'),
            fetch_farside(client)
        ]
        res=await asyncio.gather(*tasks,return_exceptions=True)
    spot,fut,oi,funding,etf=res
    if isinstance(spot,Exception): errors.append('Binance spot: '+str(spot)); spot=None
    if isinstance(fut,Exception): errors.append('Binance futures: '+str(fut)); fut=None
    if isinstance(oi,Exception): errors.append('Bybit OI: '+str(oi)); oi=None
    if isinstance(funding,Exception): errors.append('Bybit funding: '+str(funding)); funding=None
    if isinstance(etf,Exception): errors.append('Farside: '+str(etf)); etf={'status':'Unavailable','cls':'off','daily':None,'d3':None,'momentum5':None}
    if not spot or not fut:
        return {'ok':False,'errors':errors,'etf':etf}
    sdel=[kline_delta(k) for k in spot]; fdel=[kline_delta(k) for k in fut]
    sz,fz=z_last(sdel),z_last(fdel); sst,scl=flow_class(sz); fst,fcl=flow_class(fz)
    p0,p1=float(spot[-2][4]),float(spot[-1][4]); pm=(p1/p0-1)*100
    oi_state={'status':'Unavailable','cls':'off','z':0.0,'change':None}
    try:
        arr=list(reversed([float(x['openInterest']) for x in oi['result']['list']]))
        changes=[(arr[i]/arr[i-1]-1)*100 for i in range(1,len(arr))]
        oz=z_last(changes); och=changes[-1]; ost,ocl=oi_class(oz)
        oi_state={'status':ost,'cls':ocl,'z':oz,'change':och}
    except Exception as e: errors.append('OI parse: '+str(e))
    fund_state={'status':'Unavailable','cls':'off','z':0.0,'rate':None}
    try:
        arr=list(reversed([float(x['fundingRate']) for x in funding['result']['list']]))
        fuz=z_last(arr); cur=arr[-1]; ust,ucl=funding_class(fuz)
        fund_state={'status':ust,'cls':ucl,'z':fuz,'rate':cur}
    except Exception as e: errors.append('Funding parse: '+str(e))
    reg=regime_engine(pm,sz,fz,oi_state['z'],fund_state['z'],etf.get('daily'),etf.get('d3'))
    return {'ok':True,'ts':int(time.time()),'tf':tf,'price':p1,'priceMove':pm,
            'spot':{'status':sst,'cls':scl,'z':sz,'delta':sdel[-1]},
            'futures':{'status':fst,'cls':fcl,'z':fz,'delta':fdel[-1]},
            'oi':oi_state,'funding':fund_state,'etf':etf,'regime':reg,'errors':errors}


def save_snapshot(d):
    if not d.get('ok'): return
    q=text('''INSERT INTO snapshots(ts,tf,price,price_move,spot_z,futures_z,oi_z,oi_change,funding_z,funding_rate,etf_daily,etf_3d,etf_5d_momentum,regime,confidence)
              VALUES(:ts,:tf,:price,:pm,:sz,:fz,:oz,:och,:uz,:ur,:ed,:e3,:e5,:reg,:conf)''')
    with engine.begin() as conn:
        conn.execute(q,dict(ts=d['ts'],tf=d['tf'],price=d['price'],pm=d['priceMove'],sz=d['spot']['z'],fz=d['futures']['z'],oz=d['oi']['z'],och=d['oi']['change'],uz=d['funding']['z'],ur=d['funding']['rate'],ed=d['etf'].get('daily'),e3=d['etf'].get('d3'),e5=d['etf'].get('momentum5'),reg=d['regime']['regime'],conf=d['regime']['confidence']))

async def collector():
    await asyncio.sleep(3)
    while True:
        try:
            for tf in ('1h','4h','1d'):
                d=await fetch_market(tf); save_snapshot(d)
        except Exception as e:
            print('collector error',repr(e),flush=True)
        await asyncio.sleep(COLLECT_INTERVAL)

@app.on_event('startup')
async def startup():
    init_db(); asyncio.create_task(collector())

