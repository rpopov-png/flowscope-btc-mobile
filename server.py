def mean(xs): return sum(xs)/len(xs) if xs else 0.0

def stdev(xs):
    if len(xs) < 2: return 1.0
    s = statistics.pstdev(xs)
    return s if s > 1e-12 else 1.0

def z_last(xs):
    if len(xs) < 10: return 0.0
    hist=xs[:-1]
    return (xs[-1]-mean(hist))/stdev(hist)

def kline_delta(k):
    vol=float(k[5]); taker=float(k[9]); return 2*taker-vol

def flow_class(z):
    if z>1.5: return 'Strong Buy','pos'
    if z>.45: return 'Buy','pos'
    if z<-1.5: return 'Strong Sell','neg'
    if z<-.45: return 'Sell','neg'
    return 'Neutral','neu'

def oi_class(z):
    if z>1.5: return 'Sharp Rise','warn'
    if z>.4: return 'Rising','warn'
    if z<-1.5: return 'Sharp Drop','pos'
    if z<-.4: return 'Falling','pos'
    return 'Stable','neu'

def funding_class(z):
    if z>1.5: return 'High','warn'
    if z>.4: return 'Positive','warn'
    if z<-1.5: return 'Strong Negative','neg'
    if z<-.4: return 'Negative','neg'
    return 'Neutral','neu'

def etf_class(daily, d3, momentum):
    if daily is None: return 'Unavailable','off'
    if daily>0 and d3>0 and momentum>0: return 'Strong Inflow','pos'
    if daily>0 or d3>0: return 'Inflow','pos'
    if daily<0 and d3<0 and momentum<0: return 'Strong Outflow','neg'
    if daily<0 or d3<0: return 'Outflow','neg'
    return 'Neutral','neu'

